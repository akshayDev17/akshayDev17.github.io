// Copies the pinned site-themes package into this static site and writes its
// generated blocks into every HTML page. There is no bundler here, so this
// script is the homepage's build step for themes:
//
//   node scripts/sync-site-themes.mjs          rewrite the copies (after a bump)
//   node scripts/sync-site-themes.mjs --check  exit 1 if anything has drifted (CI)
//
// What it owns, and nothing else:
// - assets/site-themes/<tag>/ : themes.css plus picker.js and the modules it
//   imports, byte-for-byte from node_modules/site-themes/dist. The directory
//   carries the tag, so a bump changes every URL at once and a browser never
//   mixes a cached old module with a new one.
// - in each page, the text between the site-themes marker comments: the
//   exported bootScript inlined in <head> (so the first frame already has the
//   theme, with no request), the stylesheet link, and the picker module.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bootScript } from 'site-themes';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PKG_DIR = join(ROOT, 'node_modules', 'site-themes');
const ASSETS_DIR = join(ROOT, 'assets', 'site-themes');
// Page walk skips these, plus any directory starting with "." or "_"
// (GitHub Pages' Jekyll build does not publish those either).
const SKIP_DIRS = new Set(['node_modules', 'assets', 'scripts']);

const NOTE = 'generated by scripts/sync-site-themes.mjs from the pinned site-themes; do not edit';
const BLOCKS = {
  head: (base) => [
    `<script>${bootScript}</script>`,
    `<link rel="stylesheet" href="${base}/themes.css">`,
  ],
  picker: (base) => [
    `<script type="module">import { defineThemePicker } from '${base}/picker.js'; defineThemePicker();</script>`,
  ],
};

function readPinnedTag() {
  const spec = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).dependencies?.['site-themes'] ?? '';
  const tag = spec.match(/^github:akshayDev17\/site-themes#(v\d+\.\d+\.\d+)$/)?.[1];
  if (!tag) throw new Error(`package.json must pin site-themes as github:akshayDev17/site-themes#vX.Y.Z, found "${spec}"`);
  const installed = `v${JSON.parse(readFileSync(join(PKG_DIR, 'package.json'), 'utf8')).version}`;
  if (installed !== tag) throw new Error(`package.json pins ${tag} but node_modules has ${installed}; run npm ci`);
  return tag;
}

// themes.css plus picker.js and every module it imports, relative to dist/.
function listAssetFiles(distDir) {
  const files = ['themes.css'];
  const queue = ['picker.js'];
  while (queue.length) {
    const file = queue.shift();
    if (files.includes(file)) continue;
    files.push(file);
    const source = readFileSync(join(distDir, file), 'utf8');
    for (const [, spec] of source.matchAll(/\bfrom\s+['"]\.\/([\w.-]+\.js)['"]/g)) queue.push(spec);
  }
  return files;
}

function listPages(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      return /^[._]/.test(entry.name) || SKIP_DIRS.has(entry.name) ? [] : listPages(path);
    }
    return entry.name.endsWith('.html') ? [path] : [];
  });
}

// Replaces the text between <!-- site-themes:NAME ... --> and <!-- /site-themes:NAME -->,
// keeping the indentation of the opening marker.
function renderPage(html, page, base) {
  return Object.entries(BLOCKS).reduce((out, [name, lines]) => {
    const block = new RegExp(`^([ \\t]*)<!-- site-themes:${name}\\b[^>]*-->[\\s\\S]*?<!-- /site-themes:${name} -->`, 'm');
    if (!block.test(out)) throw new Error(`${page} has no <!-- site-themes:${name} --> … <!-- /site-themes:${name} --> block`);
    return out.replace(block, (_, indent) =>
      [`<!-- site-themes:${name} (${NOTE}) -->`, ...lines(base), `<!-- /site-themes:${name} -->`]
        .map((line) => indent + line)
        .join('\n'));
  }, html);
}

function sync({ check }) {
  const tag = readPinnedTag();
  const distDir = join(PKG_DIR, 'dist');
  const outDir = join(ASSETS_DIR, tag);
  const base = `/assets/site-themes/${tag}`;
  const drift = [];

  const staleDirs = existsSync(ASSETS_DIR) ? readdirSync(ASSETS_DIR).filter((name) => name !== tag) : [];
  for (const name of staleDirs) {
    if (check) drift.push(`assets/site-themes/${name} is not the pinned ${tag}`);
    else rmSync(join(ASSETS_DIR, name), { recursive: true, force: true });
  }

  const files = listAssetFiles(distDir);
  const shipped = existsSync(outDir) ? readdirSync(outDir) : [];
  for (const name of shipped.filter((name) => !files.includes(name))) {
    if (check) drift.push(`${relative(ROOT, join(outDir, name))} is not part of the package`);
    else rmSync(join(outDir, name), { force: true });
  }
  for (const file of files) {
    const want = readFileSync(join(distDir, file));
    const target = join(outDir, file);
    if (existsSync(target) && readFileSync(target).equals(want)) continue;
    if (check) drift.push(`${relative(ROOT, target)} differs from site-themes ${tag}`);
    else {
      mkdirSync(outDir, { recursive: true });
      writeFileSync(target, want);
    }
  }

  const pages = listPages(ROOT);
  if (pages.length === 0) throw new Error('no HTML pages found');
  for (const page of pages) {
    const html = readFileSync(page, 'utf8');
    const want = renderPage(html, relative(ROOT, page), base);
    if (want === html) continue;
    if (check) drift.push(`${relative(ROOT, page)} theme blocks differ from site-themes ${tag}`);
    else writeFileSync(page, want);
  }

  if (drift.length) {
    console.error(`site-themes copies have drifted from the pinned ${tag}:\n  ${drift.join('\n  ')}`);
    console.error('Run `npm ci && npm run themes:sync` and commit the result.');
    process.exit(1);
  }
  console.log(`site-themes ${tag}: ${files.length} asset files and ${pages.length} page(s) ${check ? 'match' : 'written'}.`);
}

sync({ check: process.argv.includes('--check') });

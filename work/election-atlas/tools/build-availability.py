#!/usr/bin/env python3
"""Write data/availability.json: which optional data files are present.

    python3 tools/build-availability.py           # rewrite data/availability.json
    python3 tools/build-availability.py --check   # exit 1 if it is out of date

The pages read this index instead of probing for files, so a view whose data has
not been added shows "not available yet" without a 404 in the console. Every
entry is derived from the files under data/; nothing here is typed by hand.

  ls.byel[year]                     results/ls/byel/{year}.json
  ls.detail[year]                   results/ls/detail/{year}.json
  cabinet.union[year].as_it_stands  cabinet/union/{year}.json
  cabinet.union[year].sworn_in      cabinet/union/{year}-sworn-in.json
  cabinet.state[S][cycle]           cabinet/state/{S}/{cycle}.json and {cycle}-sworn-in.json
  ac[S].cycles[cycle]               results/ac/{S}/{cycle}.json and {cycle}-detail.json, both
  parliament[S]                     the constituency keys of parliament/{S}/*.json
  mplads[S]                         the constituency keys of mplads/{S}/*.json (index.json aside)
  photos.ls[year]                   the geometry unique_ids of photos/ls/{year}/*.jpg

Years come from manifest.elections.ls.years and assembly cycles from
manifest.elections.ac.cycles.
"""
import json
import sys
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / 'data'
OUT = 'availability.json'


def keys_of(directory, pattern, skip=()):
    if not directory.is_dir():
        return []
    return sorted(p.stem for p in directory.glob(pattern) if p.name not in skip)


def build(data):
    manifest = json.loads((data / 'manifest.json').read_text(encoding='utf-8'))
    ls_years = manifest['elections']['ls']['years']
    cycles = manifest['elections']['ac']['cycles']
    has = lambda rel: (data / rel).is_file()
    roster = lambda base: {'sworn_in': has(f'{base}-sworn-in.json'), 'as_it_stands': has(f'{base}.json')}
    states = sorted(p.name for p in (data / 'parliament').iterdir() if p.is_dir()) \
        if (data / 'parliament').is_dir() else []
    mplads_states = sorted(p.name for p in (data / 'mplads').iterdir() if p.is_dir()) \
        if (data / 'mplads').is_dir() else []
    photo_years = sorted(p.name for p in (data / 'photos' / 'ls').iterdir() if p.is_dir()) \
        if (data / 'photos' / 'ls').is_dir() else []
    return {
        'schema': 1,
        'note': ('Which optional data files are present, generated by tools/build-availability.py '
                 'from the files under data/. A false entry, or a key that is not listed, means '
                 'that file has not been added yet; the pages say so instead of drawing it.'),
        'ls': {'byel': {str(y): has(f'results/ls/byel/{y}.json') for y in ls_years},
               'detail': {str(y): has(f'results/ls/detail/{y}.json') for y in ls_years}},
        'cabinet': {
            'union': {str(y): roster(f'cabinet/union/{y}') for y in ls_years},
            'state': {s: {str(c): roster(f'cabinet/state/{s}/{c}') for c in cs}
                      for s, cs in sorted(cycles.items())},
        },
        'ac': {s: {'cycles': {str(c): has(f'results/ac/{s}/{c}.json') and has(f'results/ac/{s}/{c}-detail.json')
                              for c in cs}}
               for s, cs in sorted(cycles.items())},
        'parliament': {s: keys_of(data / 'parliament' / s, '*.json') for s in states},
        'mplads': {s: keys_of(data / 'mplads' / s, '*.json', skip=('index.json',)) for s in mplads_states},
        'photos': {'ls': {y: keys_of(data / 'photos' / 'ls' / y, '*.jpg') for y in photo_years}},
    }


def render(doc):
    return json.dumps(doc, indent=1, ensure_ascii=False) + '\n'


def main(argv):
    text = render(build(DATA))
    path = DATA / OUT
    if '--check' in argv:
        current = path.read_text(encoding='utf-8') if path.is_file() else ''
        if current != text:
            print(f'data/{OUT} is out of date: run python3 tools/build-availability.py')
            return 1
        print(f'data/{OUT} matches the files present')
        return 0
    path.write_text(text, encoding='utf-8')
    print(f'wrote data/{OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
